local fs = require("tests.support.fs")
local process = require("tests.support.process")
local unistd = require("posix.unistd")

describe("fixture filesystem helper", function()
  local root
  before_each(function()
    root = process.tempdir()
  end)
  after_each(function()
    fs.remove(root, root)
  end)

  it("copies hidden files and paths containing spaces and quotes", function()
    fs.write(root .. "/source/.hidden/spaces 'quotes'", "fixture\000bytes")
    fs.copy(root .. "/source", root .. "/copy")
    assert.equals("fixture\000bytes", fs.read(root .. "/copy/.hidden/spaces 'quotes'"))
  end)

  it("unlinks nested and broken symlinks without following them", function()
    fs.write(root .. "/outside/keep", "preserved")
    fs.mkdir(root .. "/tree/.hidden")
    assert(unistd.link(root .. "/outside", root .. "/tree/.hidden/link", true))
    assert(unistd.link(root .. "/absent", root .. "/tree/broken", true))
    fs.remove(root .. "/tree", root)
    assert.equals("preserved", fs.read(root .. "/outside/keep"))
    assert.is_false(fs.exists(root .. "/tree"))
  end)

  it("rejects paths outside its boundary and dot segments", function()
    fs.mkdir(root .. "/tree")
    fs.write(root .. "/keep", "preserved")
    for _, path in ipairs({ root .. "/keep", root .. "/tree/../keep" }) do
      assert.has_error(function()
        fs.remove(path, root .. "/tree")
      end)
    end
    assert.equals("preserved", fs.read(root .. "/keep"))
  end)

  it("rejects cleanup through symlinked ancestors", function()
    fs.write(root .. "/outside/keep", "preserved")
    fs.mkdir(root .. "/tree")
    assert(unistd.link(root .. "/outside", root .. "/tree/link", true))
    assert.has_error(function()
      fs.remove(root .. "/tree/link/keep", root .. "/tree")
    end)
    assert.equals("preserved", fs.read(root .. "/outside/keep"))
  end)

  it("refuses to copy symlinks", function()
    fs.write(root .. "/keep", "preserved")
    assert(unistd.link(root .. "/keep", root .. "/link", true))
    assert.has_error(function()
      fs.copy(root .. "/link", root .. "/copy")
    end)
  end)
end)
